const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1536, height: 900 } }); const p = await ctx.newPage()
  const workers = []; ctx.on('serviceworker', () => {}); p.on('worker', (w) => workers.push(w.url().slice(-60)))
  await p.goto('http://localhost:3000/', { waitUntil: 'networkidle' })
  await p.evaluate((m) => m && localStorage.setItem('theorem-ui:appearance', JSON.stringify({ state: { preset: 'calm', overrides: { preview: m } }, version: 1 })), process.argv[3])
  await p.goto('http://localhost:3000/projects/' + process.argv[2], { waitUntil: 'networkidle' })
  await p.waitForTimeout(5000)
  await p.evaluate(() => { window.__long = []; new PerformanceObserver((l) => l.getEntries().forEach((e) => window.__long.push(Math.round(e.duration)))).observe({ type: 'longtask' }) })
  const cdp = await ctx.newCDPSession(p)
  await cdp.send('Profiler.enable'); await cdp.send('Profiler.setSamplingInterval', { interval: 500 }); await cdp.send('Profiler.start')
  await p.getByRole('button', { name: /^Cabinet$/ }).first().click()
  await p.waitForFunction(() => [...document.querySelectorAll('[data-artifact-cabinet] canvas')].length >= 2 && [...document.querySelectorAll('[data-artifact-cabinet] canvas')].every((c) => c.width > 0))
  await p.waitForTimeout(1500)
  const { profile } = await cdp.send('Profiler.stop')
  const self = new Map(); const byId = new Map(profile.nodes.map((n) => [n.id, n]))
  const dt = profile.timeDeltas; profile.samples.forEach((id, i) => { const n = byId.get(id); const k = (n.callFrame.functionName || '(anon)') + ' ' + n.callFrame.url.split('/').slice(-1)[0].split('?')[0]; self.set(k, (self.get(k) || 0) + (dt[i] || 0)) })
  console.log('mode', process.argv[3] ?? 'theme', 'workers', workers, 'long tasks', JSON.stringify(await p.evaluate(() => window.__long)))
  console.log([...self].sort((a, b) => b[1] - a[1]).slice(0, 25).map(([k, v]) => `${(v / 1000).toFixed(0)}ms ${k}`).join('\n'))
  await b.close()
})()
